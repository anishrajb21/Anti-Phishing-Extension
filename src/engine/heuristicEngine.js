/**
 * Heuristic Detection Engine
 * Applies rule-based cybersecurity heuristics and outputs structured risk factors.
 */

/**
 * @typedef {Object} RiskReason
 * @property {string} id
 * @property {'CRITICAL' | 'HIGH' | 'MEDIUM' | 'LOW' | 'INFO'} severity
 * @property {string} title
 * @property {string} description
 */

/**
 * Evaluates URL features against heuristic phishing detection rules.
 * 
 * @param {import('./featureExtractor.js').extractFeatures extends (...args: any[]) => infer R ? R : any} featureResult
 * @returns {{
 *   score: number,
 *   reasons: RiskReason[]
 * }}
 */
export function evaluateHeuristics(featureResult) {
  const { raw, metadata } = featureResult;
  const { parsed, impersonation } = metadata;

  let riskScore = 0;
  const reasons = [];

  // Rule 1: Userinfo / Authority '@' symbol obfuscation
  if (parsed.hasUserInfo) {
    riskScore += 30;
    reasons.push({
      id: 'AUTHORITY_OBFUSCATION',
      severity: 'CRITICAL',
      title: 'Credential Obfuscation Trick (@)',
      description: 'The URL uses embedded credentials or an @ symbol in the authority to conceal the true destination host.'
    });
  }

  // Rule 2: Brand Impersonation / Typosquatting
  if (impersonation.score >= 0.7) {
    const brandName = impersonation.impersonatedBrand || 'known brand';
    const tech = impersonation.technique || 'lookalike';
    riskScore += 35;
    reasons.push({
      id: 'BRAND_IMPERSONATION',
      severity: 'CRITICAL',
      title: `Brand Impersonation (${brandName})`,
      description: `The domain closely mimics "${brandName}" using ${tech.replace(/_/g, ' ')}.`
    });
  }

  // Rule 3: IP Address as Hostname
  if (raw.hasIP) {
    riskScore += 25;
    reasons.push({
      id: 'RAW_IP_HOST',
      severity: 'HIGH',
      title: 'Direct IP Address Host',
      description: 'The website is hosted directly on a numeric IP address instead of a registered domain name.'
    });
  }

  // Rule 4: Internationalized Domain Name (Punycode / IDN)
  if (parsed.isIDN && impersonation.score < 0.7) {
    riskScore += 15;
    reasons.push({
      id: 'IDN_PUNYCODE',
      severity: 'MEDIUM',
      title: 'Internationalized Domain (Punycode)',
      description: 'The hostname uses Punycode (xn--) or non-ASCII characters, frequently exploited for visual spoofing.'
    });
  }

  // Rule 5: Non-standard Network Port
  if (!parsed.isStandardPort) {
    riskScore += 15;
    reasons.push({
      id: 'NON_STANDARD_PORT',
      severity: 'MEDIUM',
      title: `Unusual Port (${parsed.port})`,
      description: `The URL connects over port ${parsed.port} rather than standard HTTP (80) or HTTPS (443).`
    });
  }

  // Rule 6: Suspicious or High-Abuse TLD
  if (raw.hasSuspiciousTLD) {
    riskScore += 15;
    reasons.push({
      id: 'SUSPICIOUS_TLD',
      severity: 'MEDIUM',
      title: `High-Risk TLD (.${parsed.domain.publicSuffix})`,
      description: 'The domain uses an extension with statistically elevated rates of disposable abuse and malware hosting.'
    });
  }

  // Rule 7: Excessive Subdomains / Deep Nesting
  if (raw.numDots > 3) {
    riskScore += 15;
    reasons.push({
      id: 'EXCESSIVE_SUBDOMAINS',
      severity: 'MEDIUM',
      title: 'Excessive Subdomain Nesting',
      description: `The hostname contains ${raw.numDots} dot separators, often used to camouflage attacker-controlled domains.`
    });
  } else if (raw.numDots === 3) {
    riskScore += 8;
  }

  // Rule 8: High Hyphen Count (Combosquatting)
  if (raw.numHyphens > 2) {
    riskScore += 12;
    reasons.push({
      id: 'EXCESSIVE_HYPHENS',
      severity: 'LOW',
      title: 'Multiple Hyphens in Hostname',
      description: 'Multiple hyphens in domain names are frequently seen in phishing kits and spoofed login panels.'
    });
  }

  // Rule 9: High Domain Entropy (DGA / Randomness)
  if (raw.domainEntropy > 4.2 && raw.hostnameLength > 12) {
    riskScore += 10;
    reasons.push({
      id: 'HIGH_ENTROPY_DOMAIN',
      severity: 'LOW',
      title: 'Unusually Random Domain Name',
      description: 'The hostname exhibits high algorithmic randomness (Shannon entropy), characteristic of Domain Generation Algorithms (DGA).'
    });
  }

  // Rule 10: Excessive Digits in Domain
  if (raw.numDigits > 3 && !raw.hasIP) {
    riskScore += 10;
    reasons.push({
      id: 'NUMERIC_SUBSTRINGS',
      severity: 'LOW',
      title: 'High Numeric Content in Host',
      description: 'The domain contains multiple numeric characters, commonly generated by automated phishing campaigns.'
    });
  }

  // Rule 11: Insecure Plaintext HTTP Protocol
  if (!raw.hasHTTPS) {
    riskScore += 10;
    reasons.push({
      id: 'INSECURE_HTTP',
      severity: 'INFO',
      title: 'Unencrypted Connection (HTTP)',
      description: 'Communication is not protected by TLS encryption, making credentials vulnerable to network interception.'
    });
  }

  // Rule 12: Suspicious Length
  if (raw.urlLength > 120) {
    riskScore += 10;
    reasons.push({
      id: 'EXCESSIVE_URL_LENGTH',
      severity: 'LOW',
      title: 'Abnormally Long URL',
      description: 'Extremely long URLs (>120 chars) are often used to conceal malicious payload parameters.'
    });
  }

  return {
    score: Math.min(riskScore, 100),
    reasons
  };
}
